#!/usr/bin/env python3
"""Convert a TTF font into a LovyanGFX GFXfont header with Latin and Cyrillic glyphs.

The glyphs are 1-bit, as in the built-in DejaVu fonts. Run it with a Python that has Pillow:

    python3 scripts/make_font.py /usr/share/fonts/TTF/OpenSans-Regular.ttf 16 OpenSans16 lib/Ui/src/OpenSans16.h
"""

import argparse

from PIL import ImageFont

# Printable ASCII, Ё, А-я, ё. Each range is (first, last) code point.
RANGES = [(0x20, 0x7E), (0x401, 0x401), (0x410, 0x44F), (0x451, 0x451)]


def glyph(font, code):
    char = chr(code)
    mask, (x_offset, y_offset) = font.getmask2(char, mode="1", anchor="ls")
    width, height = mask.size
    bits = [1 if mask.getpixel((x, y)) else 0 for y in range(height) for x in range(width)]
    advance = round(font.getlength(char))
    if not any(bits):
        return [], (0, 0, advance, 0, 0)
    return bits, (width, height, advance, x_offset, y_offset)


def pack(bits):
    data = []
    for i in range(0, len(bits), 8):
        chunk = bits[i : i + 8] + [0] * (8 - len(bits[i : i + 8]))
        data.append(sum(bit << (7 - n) for n, bit in enumerate(chunk)))
    return data


def convert(ttf, size, name):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    bitmap, glyphs, ranges = [], [], []
    for first, last in RANGES:
        ranges.append((first, last, len(glyphs)))
        for code in range(first, last + 1):
            bits, (width, height, advance, x_offset, y_offset) = glyph(font, code)
            glyphs.append((len(bitmap), width, height, advance, x_offset, y_offset, code))
            bitmap.extend(pack(bits))
    lines = [
        f"// {name}: generated by scripts/make_font.py from {ttf.split('/')[-1]} at {size} px.",
        "// Open Sans is licensed under the SIL Open Font License 1.1: https://openfontlicense.org",
        "#pragma once",
        "",
        "#include <M5GFX.h>",
        "",
        f"inline const uint8_t {name}Bitmaps[] = {{",
    ]
    for i in range(0, len(bitmap), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in bitmap[i : i + 16]) + ",")
    lines += ["};", "", f"inline const lgfx::GFXglyph {name}Glyphs[] = {{"]
    for offset, width, height, advance, x_offset, y_offset, code in glyphs:
        lines.append(f"    {{{offset}, {width}, {height}, {advance}, {x_offset}, {y_offset}}},  // U+{code:04X}")
    lines += ["};", "", f"inline const lgfx::EncodeRange {name}Ranges[] = {{"]
    lines += [f"    {{0x{first:X}, 0x{last:X}, {base}}}," for first, last, base in ranges]
    lines += [
        "};",
        "",
        f"inline const lgfx::GFXfont {name}((uint8_t*){name}Bitmaps, (lgfx::GFXglyph*){name}Glyphs, "
        f"0x{RANGES[0][0]:X}, 0x{RANGES[-1][1]:X}, {ascent + descent}, {len(ranges)}, (lgfx::EncodeRange*){name}Ranges);",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("ttf", help="TTF or OTF font file")
    parser.add_argument("size", type=int, help="Font size in pixels")
    parser.add_argument("name", help="C++ name of the font, for example OpenSans16")
    parser.add_argument("output", help="Header file to write")
    args = parser.parse_args()
    header = convert(args.ttf, args.size, args.name)
    with open(args.output, "w", encoding="utf-8") as out:
        out.write(header)


if __name__ == "__main__":
    main()
